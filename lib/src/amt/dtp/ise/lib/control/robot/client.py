"""Client for the RobotAPI (see :mod:`.server`): a :class:`~..segment.client.SegmentClient` (every segment
method) plus the robot routes and the kinematics service routes (:class:`~..motion.client.KinematicsClient`).

Usually used through the typed subclass in the client module generated by the API
(``GET /api/segment/models.py``)::

    from amt_mr_a1 import *

    client = Client("http://isaac-host:8020")
    client.robot_write([RobotCommand(frame_id=1, robots={"arm": LinMove(target=pose, velocity=0.1)})])
    with client.robot_stream(executed_only=True) as stream:
        for frame in stream:            # RobotResponseFrame: frame.frame (segment), frame.robots[...]
            ...

Only depends on requests and pydantic.
"""
from typing import Any, ClassVar, Dict, List, Optional, Sequence, Type, TypeVar, Union

from pydantic import BaseModel

from ..motion.client import KinematicsClient
from ..segment.client import SegmentClient, SegmentStream
from .models import (
    RobotApiInfo,
    RobotCommandBase,
    RobotCommandResponse,
    RobotCompileResponseBase,
    RobotConfig,
    RobotClearResponse,
    RobotConfiguration,
    RobotPlanRequest,
    RobotPlanResponse,
    RobotResponseFrameBase,
)


TC = TypeVar("TC", bound=BaseModel)
TS = TypeVar("TS", bound=BaseModel)

ROBOT_PATH = "/robot"


class RobotClient(SegmentClient[TC, TS], KinematicsClient):
    """Client for a RobotApi. See :class:`SegmentClient` for the constructor; the robot models come from
    the generated module's class attributes, or are derived from the segment models."""

    robot_command_model: ClassVar[Optional[Type[BaseModel]]] = None
    robot_response_frame_model: ClassVar[Optional[Type[BaseModel]]] = None
    robot_compile_response_model: ClassVar[Optional[Type[BaseModel]]] = None

    def __init__(self, base_url: str = "http://127.0.0.1:8020", commands_model: Optional[Type[TC]] = None,
                 states_model: Optional[Type[TS]] = None, **kwargs: Any):
        super().__init__(base_url, commands_model, states_model, **kwargs)
        cls = type(self)
        if cls.robot_command_model is not None and self.command_frame_model is cls.command_frame_model:
            self.robot_command_model = cls.robot_command_model
            self.robot_response_frame_model = cls.robot_response_frame_model
            self.robot_compile_response_model = cls.robot_compile_response_model
        else:
            self.robot_command_model = RobotCommandBase[self.commands_model]
            self.robot_response_frame_model = RobotResponseFrameBase[self.response_frame_model]
            self.robot_compile_response_model = RobotCompileResponseBase[self.command_frame_model]

    def _commands_json(self, commands: Any) -> List[Dict[str, Any]]:
        if isinstance(commands, (BaseModel, dict)):
            commands = [commands]
        result = []
        for command in commands:
            if not isinstance(command, self.robot_command_model):
                command = self.robot_command_model.model_validate(command, from_attributes=True)
            result.append(command.model_dump(mode="json", exclude_unset=True))
        return result

    # ---- API ------------------------------------------------------------------------------------

    def robot_info(self) -> RobotApiInfo:
        """The robots: components, joints with effective limits, frames, tool frames, jump-check parameters."""
        return RobotApiInfo.model_validate(self._request("GET", f"{ROBOT_PATH}/info").json())

    def robot_compile(self, commands: Union[BaseModel, Dict[str, Any], Sequence[Any]],
                      start: Optional[Dict[str, Dict[str, float]]] = None, dt: Optional[float] = None) -> BaseModel:
        """Compile robot commands into segment command frames, without queueing them: from the end of the queue, or
        from ``start`` (``{robot: {joint: deg or m}}``, e.g. a previous compile's ``end``) and/or at ``dt``. The answer's
        ``queue_revision`` goes to ``write(..., expected_revision=)``. ``start``, ``dt``, ``queue_revision``, and ``end``
        are a preview feature (deferred): only a RobotApi with ``preview_features=True`` serves them."""
        body: Any = self._commands_json(commands)
        if start is not None or dt is not None:
            body = {"commands": body, **({"start": start} if start is not None else {}), **({"dt": dt} if dt is not None else {})}
        response = self._request("POST", f"{ROBOT_PATH}/process/compile", json=body, timeout=max(self._timeout, 60.0))
        return self.robot_compile_response_model.model_validate_json(response.content)

    def robot_plan(self, robot: str, move: Union[BaseModel, Dict[str, Any]], start: Optional[Dict[str, float]] = None,
                   include_samples: bool = False) -> RobotPlanResponse:
        """Plan one robot's collision-free move (a ``PlanMove``) without queueing it."""
        request = RobotPlanRequest(robot=robot, move=move if isinstance(move, BaseModel) else move, start=start,
                                   include_samples=include_samples)
        response = self._request("POST", f"{ROBOT_PATH}/process/plan", json=request.model_dump(mode="json", exclude_unset=True),
                                 timeout=max(self._timeout, 60.0))
        return RobotPlanResponse.model_validate(response.json())

    def robot_clear(self, stop: str = "hold") -> RobotClearResponse:
        """Clear the queue with a stop policy: ``hold`` or ``decelerate`` (moving robots ramp to rest)."""
        return RobotClearResponse.model_validate(self._request("DELETE", f"{ROBOT_PATH}/process/clear",
                                                               params={"stop": stop}).json())

    def robot_write(self, commands: Union[BaseModel, Dict[str, Any], Sequence[Any]]) -> RobotCommandResponse:
        """Compile robot commands and queue their frames (all or nothing). Raises :class:`CoreApiError` with
        ``code`` IK_UNREACHABLE, JOINT_JUMP, ... (422) if any can't be compiled."""
        response = self._request("POST", f"{ROBOT_PATH}/process/write", json=self._commands_json(commands),
                                 timeout=max(self._timeout, 60.0))
        return RobotCommandResponse.model_validate(response.json())

    def robot_execute(self, command: Union[BaseModel, Dict[str, Any]], timeout: float = 60.0) -> BaseModel:
        """Compile one robot command, queue it, and block until its last frame has been applied; returns
        that step's robot frame."""
        response = self._request("POST", f"{ROBOT_PATH}/process/execute", params={"timeout": timeout},
                                 json=self._commands_json(command)[0], timeout=timeout + max(self._timeout, 60.0))
        return self.robot_response_frame_model.model_validate_json(response.content)

    def robot_read(self) -> BaseModel:
        """The latest step's robot frame (the segment's response frame and each robot's TCP poses)."""
        return self.robot_response_frame_model.model_validate_json(self._request("GET", f"{ROBOT_PATH}/process/read").content)

    def robot_stream(self, every: int = 1, executed_only: bool = False, resume_after: Optional[int] = None,
                     instance_id: Optional[str] = None, clamp: bool = False, events: bool = False) -> SegmentStream:
        """Like :meth:`stream`, but frames are robot frames (``RobotResponseFrame``)."""
        url = self._url(f"{ROBOT_PATH}/stream")
        params: Dict[str, Any] = {"every": every, "executed_only": str(executed_only).lower()}
        if resume_after is not None:
            params["resume_after"] = resume_after
            if instance_id is not None:
                params["instance_id"] = instance_id
            if clamp:
                params["clamp"] = "true"
        response = self._session.get(url, params=params, stream=True, timeout=(self._timeout, None),
                                     headers={"Accept": "text/event-stream"})
        self._raise_for(response, "GET", url)
        return SegmentStream(response, self.robot_response_frame_model, events=events)

    def robot_config_read(self) -> RobotConfiguration:
        return RobotConfiguration.model_validate(self._request("GET", f"{ROBOT_PATH}/config/read").json())

    def robot_config_write(self, robots: Dict[str, Union[RobotConfig, Dict[str, Any]]]) -> RobotConfiguration:
        """Set robots' active tool frame and/or TCP offset (``{robot id: RobotConfig}``); returns the result."""
        body = RobotConfiguration(robots={id: RobotConfig.model_validate(c) if isinstance(c, dict) else c
                                          for id, c in robots.items()})
        response = self._request("POST", f"{ROBOT_PATH}/config/write", json=body.model_dump(mode="json", exclude_unset=True))
        return RobotConfiguration.model_validate(response.json())
