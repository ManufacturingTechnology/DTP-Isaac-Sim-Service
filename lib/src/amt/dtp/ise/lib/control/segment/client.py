"""Client for the segment API (see :mod:`amt.dtp.ise.lib.control.segment.server`).

Usually used through the typed subclass in the client module generated for the API (download it
from ``GET /api/segment/models.py``, or with :func:`download_client_module`)::

    from machining_cell import *

    client = Client("http://isaac-host:8020")                  # checks the schema fingerprint
    state = client.read()                                      # ResponseFrame
    client.write([CommandFrame(frame_id=1, components=ComponentCommands(
        mill=AmtVmA1Commands(...), robot=AmtMrA1Commands(...))), ...])
    with client.stream() as stream:
        for response in stream:
            ...

Only depends on requests and pydantic (not on the server's fastapi/uvicorn).
"""
import json
import warnings
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, ClassVar, Dict, Generic, Iterator, List, Optional, Sequence, Type, TypeVar, Union

import requests
from pydantic import BaseModel

from ..core.client import CoreApiError, CoreClient
from .models import (
    BufferHeader,
    CommandFrameBase,
    CommandResponseBase,
    ConfigEvent,
    ConfigurationBase,
    ErrorEvent,
    Heartbeat,
    ResetEvent,
    ResponseFrameBase,
    RetransmitResponse,
    SegmentError,
    SegmentInfo,
    SegmentPreviewInfo,
    SegmentStatus,
    StatusEvent,
)


TC = TypeVar("TC", bound=BaseModel)
TS = TypeVar("TS", bound=BaseModel)

SEGMENT_PATH = "/segment"


class SchemaMismatch(Exception):
    """The API's models changed since the client models were generated."""


class SegmentStreamError(CoreApiError):
    """The stream sent an ``error`` event (e.g. STREAM_OVERFLOW) and ended. ``errors`` are the typed
    errors, ``header`` the retransmission buffer's state; resume with ``resume_after`` to continue."""

    def __init__(self, event: ErrorEvent, url: str = ""):
        self.errors: List[SegmentError] = event.errors
        self.header: Optional[BufferHeader] = event.header
        first = event.errors[0] if event.errors else None
        detail = {"code": first.code if first else None, "message": first.message if first else "stream error"}
        super().__init__(200, detail, "GET", url)


def download_client_module(base_url: str, directory: Union[str, Path] = ".", file_name: Optional[str] = None) -> Path:
    """Download the client module generated by a segment API (``models.py``) into ``directory``, under
    the file name the API suggests (e.g. ``machining_cell.py``) unless ``file_name`` is given. Returns
    the file's path; import it to use its models and client class."""
    url = f"{base_url.rstrip('/')}/api{SEGMENT_PATH}/models.py"
    response = requests.get(url, timeout=30)
    if response.status_code >= 400:
        raise CoreApiError(response.status_code, response.text, "GET", url)
    if file_name is None:
        disposition = response.headers.get("content-disposition", "")
        file_name = disposition.split('filename="', 1)[1].split('"', 1)[0] if 'filename="' in disposition else "segment_models.py"
    path = Path(directory) / file_name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(response.text, encoding="utf-8")
    return path


class SegmentStream:
    """An open Server-Sent Events stream. Iterate it to receive response frames (and, with
    ``events=True``, also :class:`ConfigEvent`, :class:`StatusEvent`, and :class:`ResetEvent`); close it
    (or use it as a context manager) to disconnect.

    The stream remembers ``instance_id`` and ``last_sequence`` (of the last sequenced event received)
    and ``next_sequence`` (from heartbeats), so a client can reconnect with
    ``client.stream(resume_after=stream.last_sequence, instance_id=stream.instance_id)``. An ``error``
    event raises :class:`SegmentStreamError`."""

    def __init__(self, response: requests.Response, response_frame_model: Type[BaseModel], events: bool = False):
        self._response = response
        self._response_frame_model = response_frame_model
        self._events = events
        self.instance_id: Optional[str] = None
        self.last_sequence: Optional[int] = None
        self.next_sequence: Optional[int] = None

    def _parse(self, event: str, payload: str) -> Optional[BaseModel]:
        if event == "frame":
            return self._response_frame_model.model_validate_json(payload)
        if event == "config":
            return ConfigEvent.model_validate_json(payload) if self._events else None
        if event == "status":
            return StatusEvent.model_validate_json(payload) if self._events else None
        if event == "reset":
            reset = ResetEvent.model_validate_json(payload)
            self.instance_id = reset.header.instance_id
            return reset if self._events else None
        if event == "heartbeat":
            heartbeat = Heartbeat.model_validate_json(payload)
            self.instance_id, self.next_sequence = heartbeat.instance_id, heartbeat.next_sequence
            return None
        if event == "error":
            raise SegmentStreamError(ErrorEvent.model_validate_json(payload), self._response.url)
        return None  # an event type this client doesn't know (newer server)

    def __iter__(self) -> Iterator[BaseModel]:
        buffer = ""
        event = "message"
        event_id: Optional[str] = None
        data: List[str] = []
        try:
            # chunk_size=None yields data as soon as it arrives instead of filling a buffer first.
            for chunk in self._response.iter_content(chunk_size=None, decode_unicode=True):
                if isinstance(chunk, bytes):
                    chunk = chunk.decode("utf-8")
                buffer += chunk
                while "\n" in buffer:
                    line, buffer = buffer.split("\n", 1)
                    line = line.rstrip("\r")
                    if line == "":
                        if data:
                            if event_id is not None:
                                instance, _, sequence = event_id.partition(":")
                                if sequence.isdigit():
                                    self.instance_id, self.last_sequence = instance, int(sequence)
                                    self.next_sequence = self.last_sequence + 1
                            item = self._parse(event, "\n".join(data))
                            if item is not None:
                                yield item
                        event, event_id, data = "message", None, []
                    elif line.startswith(":"):
                        continue  # comment
                    else:
                        name, _, value = line.partition(":")
                        value = value[1:] if value.startswith(" ") else value
                        if name == "event":
                            event = value
                        elif name == "data":
                            data.append(value)
                        elif name == "id":
                            event_id = value
        except (requests.exceptions.ChunkedEncodingError, requests.exceptions.ConnectionError, AttributeError):
            if not self._response.raw or self._response.raw.closed:
                return  # closed by close()
            raise

    def close(self) -> None:
        self._response.close()

    def __enter__(self) -> "SegmentStream":
        return self

    def __exit__(self, *exc: Any) -> None:
        self.close()


@dataclass
class Retransmission:
    """The result of :meth:`SegmentClient.retransmit`, with the events parsed: response frames,
    :class:`ConfigEvent` and :class:`StatusEvent` models, in sequence order."""
    header: BufferHeader
    events: List[BaseModel] = field(default_factory=list)
    missing: List[int] = field(default_factory=list)
    truncated: bool = False


class SegmentClient(CoreClient, Generic[TC, TS]):
    """Client for a segment API.

    Use the typed subclass from the generated client module, which sets the models as class
    attributes along with the fingerprint it was generated from; or pass the API's component commands
    and component states models (``api.component_commands_model``, ``api.component_states_model``).

    :param base_url: The API's address, e.g. ``http://isaac-host:8020``.
    :param verify: Check on connect that the API's schema fingerprint matches the one the client
        models were generated from.
    :param strict: Raise :class:`SchemaMismatch` on a mismatch (otherwise warn).
    :param timeout: Timeout in seconds for ordinary requests.
    """

    API_TITLE: ClassVar[Optional[str]] = None
    API_VERSION: ClassVar[Optional[str]] = None
    SCHEMA_FINGERPRINT: ClassVar[Optional[str]] = None
    commands_model: ClassVar[Optional[Type[BaseModel]]] = None
    states_model: ClassVar[Optional[Type[BaseModel]]] = None
    configs_model: ClassVar[Optional[Type[BaseModel]]] = None
    configuration_model: ClassVar[Optional[Type[BaseModel]]] = None
    command_frame_model: ClassVar[Optional[Type[BaseModel]]] = None
    response_frame_model: ClassVar[Optional[Type[BaseModel]]] = None
    command_response_model: ClassVar[Optional[Type[BaseModel]]] = None

    def __init__(
        self,
        base_url: str = "http://127.0.0.1:8020",
        commands_model: Optional[Type[TC]] = None,
        states_model: Optional[Type[TS]] = None,
        *,
        configs_model: Optional[Type[BaseModel]] = None,
        verify: bool = True,
        strict: bool = True,
        timeout: float = 10.0,
    ):
        super().__init__(base_url, timeout)
        cls = type(self)
        commands_model = commands_model or cls.commands_model
        states_model = states_model or cls.states_model
        if commands_model is None or states_model is None:
            raise TypeError(
                "commands_model and states_model are required (or use the client class from the generated "
                "client module, which sets them; see download_client_module)"
            )
        self.commands_model = commands_model
        self.states_model = states_model
        self.configs_model = configs_model or cls.configs_model
        if cls.command_frame_model is not None and commands_model is cls.commands_model and states_model is cls.states_model:
            self.command_frame_model = cls.command_frame_model
            self.response_frame_model = cls.response_frame_model
            self.command_response_model = cls.command_response_model or CommandResponseBase
            self.configuration_model = cls.configuration_model
        else:
            self.command_frame_model = CommandFrameBase[commands_model]
            self.response_frame_model = ResponseFrameBase[states_model]
            self.command_response_model = CommandResponseBase
            self.configuration_model = ConfigurationBase[self.configs_model] if self.configs_model is not None else None
        if verify:
            self.verify(strict=strict)

    # ---- helpers ------------------------------------------------------------------------------

    def _frames_json(self, frames: Any) -> List[Dict[str, Any]]:
        if isinstance(frames, (BaseModel, dict)):
            frames = [frames]
        return [self._frame(f).model_dump(mode="json", exclude_unset=True) for f in frames]

    def _frame(self, frame: Any) -> BaseModel:
        if isinstance(frame, self.command_frame_model):
            return frame
        if isinstance(frame, self.commands_model):
            return self.command_frame_model(components=frame)
        return self.command_frame_model.model_validate(frame, from_attributes=True)

    def _event_model(self, event: str, data: Dict[str, Any]) -> BaseModel:
        if event == "frame":
            return self.response_frame_model.model_validate(data)
        if event == "config":
            return ConfigEvent.model_validate(data)
        return StatusEvent.model_validate(data)

    # ---- API ------------------------------------------------------------------------------------

    def segment_info(self) -> SegmentInfo:
        """The API's components, schema fingerprint, queue and halt status, and retransmission buffer."""
        info = self._request("GET", f"{SEGMENT_PATH}/info").json()
        return (SegmentPreviewInfo if "queue_revision" in info else SegmentInfo).model_validate(info)

    def verify(self, strict: bool = True) -> SegmentInfo:
        """Check that the API's schema fingerprint matches the one the client models were generated
        from. Raises :class:`SchemaMismatch` (or warns, if not ``strict``)."""
        info = self.segment_info()
        expected = type(self).SCHEMA_FINGERPRINT
        if expected is not None and info.fingerprint != expected:
            bumped = "" if info.version != type(self).API_VERSION else " (the version was not bumped)"
            message = (
                f"The segment API '{info.title}' changed since its client models were generated:\n"
                f"  generated: v{type(self).API_VERSION} {expected}\n"
                f"  server:    v{info.version} {info.fingerprint}{bumped}\n"
                f"Download fresh client models from {self._url(SEGMENT_PATH + '/models.py')}"
            )
            if strict:
                raise SchemaMismatch(message)
            warnings.warn(message, stacklevel=2)
        return info

    def models_source(self) -> str:
        """The client module generated by the API (the contents of ``models.py``)."""
        return self._request("GET", f"{SEGMENT_PATH}/models.py").text

    def read(self) -> BaseModel:
        """The response frame of the latest simulation step."""
        return self.response_frame_model.model_validate_json(self._request("GET", f"{SEGMENT_PATH}/process/read").content)

    def write(self, frames: Union[BaseModel, Dict[str, Any], Sequence[Union[BaseModel, Dict[str, Any]]]],
              expected_revision: Optional[int] = None) -> BaseModel:
        """Append command frames to the queue (one is applied per simulation step).

        Accepts one frame or a sequence of frames. A frame can be a command frame model, a component
        commands model (wrapped in a frame without a frame_id), or an equivalent dict. Returns the
        command response (accepted, queue length, halted). With ``expected_revision`` (a compile's
        ``queue_revision``), the frames are appended only if the queue hasn't changed since (else
        :class:`CoreApiError` 409 ``QUEUE_CHANGED``); a preview feature (deferred): a server without
        ``preview_features=True`` refuses it (400).
        """
        params = {"expected_revision": expected_revision} if expected_revision is not None else None
        response = self._request("POST", f"{SEGMENT_PATH}/process/write", json=self._frames_json(frames), params=params)
        return self.command_response_model.model_validate(response.json())

    def clear(self) -> List[BaseModel]:
        """Remove every command frame from the queue and return them (also releases a halt). The
        actuators keep their last commands."""
        return [self.command_frame_model.model_validate(f)
                for f in self._request("DELETE", f"{SEGMENT_PATH}/process/clear").json()]

    def resume(self) -> SegmentStatus:
        """Release a halt (after a failed frame), or a pause: queued frames run again."""
        return SegmentStatus.model_validate(self._request("POST", f"{SEGMENT_PATH}/process/resume").json())

    def pause(self) -> SegmentStatus:
        """Pause the queue without clearing it: queued frames wait until :meth:`resume`. A preview feature (deferred): only a server with ``preview_features=True`` serves it (else 404)."""
        return SegmentStatus.model_validate(self._request("POST", f"{SEGMENT_PATH}/process/pause").json())

    def execute(self, frame: Union[BaseModel, Dict[str, Any]], timeout: float = 30.0) -> BaseModel:
        """Append one frame to the queue and block until it has been applied; returns the response
        frame of that step. Raises :class:`CoreApiError` with ``code == "HALTED"`` (409) while halted."""
        body = self._frames_json(frame)[0]
        response = self._request("POST", f"{SEGMENT_PATH}/process/execute", params={"timeout": timeout}, json=body,
                                 timeout=timeout + self._timeout)
        return self.response_frame_model.model_validate_json(response.content)

    def config_read(self) -> Union[BaseModel, Dict[str, Any]]:
        """The configuration (``Configuration``: instance_id, config_revision, components)."""
        data = self._request("GET", f"{SEGMENT_PATH}/config/read").json()
        return self.configuration_model.model_validate(data) if self.configuration_model is not None else data

    def config_write(self, value: Union[BaseModel, Dict[str, Any]], timeout: float = 10.0) -> ConfigEvent:
        """Write configuration (``ComponentConfigs`` or a dict; only what is sent changes) and wait until
        the next step boundary has applied it. Returns the outcome per component and transducer, the
        new ``config_revision``, and the first response frame that runs with it."""
        if isinstance(value, dict) and self.configs_model is not None:
            value = self.configs_model.model_validate(value)
        body = value.model_dump(mode="json", exclude_unset=True) if isinstance(value, BaseModel) else value
        response = self._request("POST", f"{SEGMENT_PATH}/config/write", params={"timeout": timeout}, json=body,
                                 timeout=timeout + self._timeout)
        return ConfigEvent.model_validate(response.json())

    def stream(
        self,
        every: int = 1,
        executed_only: bool = False,
        resume_after: Optional[int] = None,
        instance_id: Optional[str] = None,
        clamp: bool = False,
        events: bool = False,
    ) -> SegmentStream:
        """Open a stream of response frames (one per simulation step, or every ``every``-th; only steps
        that applied a frame if ``executed_only``). With ``events``, the stream also yields config,
        status, and reset events.

        ``resume_after`` (with the ``instance_id`` it belongs to) resumes after a disconnect: buffered
        events after that sequence come first. Raises :class:`CoreApiError` with ``code ==
        "OUT_OF_RANGE"`` if they are no longer buffered, unless ``clamp`` (then the stream starts with a
        reset event and the oldest buffered event)."""
        url = self._url(f"{SEGMENT_PATH}/stream")
        params: Dict[str, Any] = {"every": every, "executed_only": str(executed_only).lower()}
        if resume_after is not None:
            params["resume_after"] = resume_after
            if instance_id is not None:
                params["instance_id"] = instance_id
            if clamp:
                params["clamp"] = "true"
        response = self._session.get(
            url,
            params=params,
            stream=True,
            timeout=(self._timeout, None),
            headers={"Accept": "text/event-stream"},
        )
        self._raise_for(response, "GET", url)
        return SegmentStream(response, self.response_frame_model, events=events)

    def retransmit(
        self,
        sequences: Optional[Sequence[int]] = None,
        from_: Optional[int] = None,
        to: Optional[int] = None,
        count: Optional[int] = None,
        clamp: bool = False,
        instance_id: Optional[str] = None,
    ) -> Retransmission:
        """Fetch buffered events to repair a stream: by a list of ``sequences`` (those not buffered are
        returned in ``missing``) or by an inclusive range ``from_``..``to``."""
        params: Dict[str, Any] = {}
        if sequences is not None:
            params["sequences"] = ",".join(str(int(s)) for s in sequences)
        if from_ is not None:
            params["from"] = from_
        if to is not None:
            params["to"] = to
        if count is not None:
            params["count"] = count
        if clamp:
            params["clamp"] = "true"
        if instance_id is not None:
            params["instance_id"] = instance_id
        result = RetransmitResponse.model_validate(self._request("GET", f"{SEGMENT_PATH}/retransmit", params=params).json())
        return Retransmission(header=result.header, missing=result.missing, truncated=result.truncated,
                              events=[self._event_model(e.event, e.data) for e in result.events])
